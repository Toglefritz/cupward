import 'dart:async';

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_app_check/firebase_app_check.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
import 'package:material_ui/material_ui.dart';

import 'app.dart';
import 'firebase_options.dart';
import 'services/auth/auth_service.dart';
import 'services/firebase_emulator/dev_machine_ip.dart';
import 'services/scale/demo_launch.dart';
import 'services/scale/scale_service.dart';

/// The reCAPTCHA Enterprise site key used by App Check in release builds on the web.
///
/// It is supplied at build time with `--dart-define=RECAPTCHA_SITE_KEY=<key>` so that it is not committed. The site key
/// is not a secret, because it is sent to every browser, but each environment registers its own.
const String _recaptchaSiteKey = String.fromEnvironment('RECAPTCHA_SITE_KEY');

/// Whether debug builds connect to the local Firebase Emulator Suite, set with
/// `--dart-define=USE_FIREBASE_EMULATOR=true`. It is false when the flag is not given.
const bool _useFirebaseEmulator = bool.fromEnvironment('USE_FIREBASE_EMULATOR');

/// A Firebase App Check debug token to use while running the app in debug mode.
///
/// Firebase App Check creates cryptographically-secure JWT tokens that allow backend resources to confirm that
/// requests and other interactions originate from a genuine, unmodified version of the Cupward app running on
/// unmodified target devices. However, during debug builds, because debug builds are signed differently that release
/// builds, the Firebase App Check Flutter plugin generates a debug token. This debug token must be registered in the
/// Firebase console to allow the App Check system to authenticate the debug builds.
///
/// The Firebase App Check debug token can change over time under various conditions. This can create some
/// inconveniences during development and CI operations. Therefore, this flag allows a stable App Check debug token to
/// be defined so that every time the app runs, the same token is used. This removes the need to constantly update the
/// debug tokens stored in the Firebase console.
///
/// The App Check debug token specified in this environment variable must be registered in the Firebase console in
/// advance of running the app. Additionally, it should be kept secret, which is why the app accepts it in an argument
/// to app builds rather than hard-coding the token into the codebase.
const String _appCheckDebugToken = String.fromEnvironment('APP_CHECK_DEBUG_TOKEN');

/// The port of the Auth emulator, matching `cupward_cloud/firebase.json`.
const int _authEmulatorPort = 9099;

/// The port of the Firestore emulator, matching `cupward_cloud/firebase.json`.
const int _firestoreEmulatorPort = 8080;

/// The App Check provider for release builds on the web, or null when no site key was supplied.
///
/// Without a provider, App Check is not activated in the browser, and Firebase services that enforce App Check reject
/// the app's requests. Native platforms ignore this value.
WebProvider? get _releaseWebProvider =>
    _recaptchaSiteKey.isEmpty ? null : ReCaptchaEnterpriseProvider(_recaptchaSiteKey);

/// Application entry point that initializes Firebase and runs the Flutter app.
///
/// Firebase is initialized first, followed by Firebase App Check, so that every Firebase service added later is
/// protected from the first request. In debug builds launched with `--dart-define=USE_FIREBASE_EMULATOR=true`, Firebase
/// Auth and Cloud Firestore then connect to the local Firebase Emulator Suite, at the host given by `devMachineIP` in
/// _services/firebase_emulator/dev_machine_ip.dart_. Firebase AI Logic has no emulator, so AI requests still reach the
/// cloud.
///
/// Last, the app starts signing in anonymously through `AuthService`. It does not wait for the result, so a launch
/// without a network is not held up. Code that needs the user waits for it then. All other application configuration
/// is handled by the Cupward widget in `app.dart`.
Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize Firebase using the platform-specific options generated by the FlutterFire CLI. See FIREBASE_SETUP.md.
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Initialize Firebase App Check. Debug builds use the debug providers, whose tokens must be registered in the
  // Firebase console (the debug token is printed to the console on first launch, and to the browser console on the
  // web). Release builds use the default attestation providers (Play Integrity on Android, DeviceCheck on Apple
  // platforms), and reCAPTCHA Enterprise on the web with the site key given at build time. See FIREBASE_SETUP.md.
  //
  // Stable debug tokens can be provided using a `--dart-define` flag, as detailed above.
  if (kDebugMode) {
    await FirebaseAppCheck.instance.activate(
      providerAndroid: const AndroidDebugProvider(
        debugToken: _appCheckDebugToken,
      ),
      providerApple: const AppleDebugProvider(
        debugToken: _appCheckDebugToken,
      ),
      providerWeb: WebDebugProvider(
        debugToken: _appCheckDebugToken,
      ),
    );
  } else {
    await FirebaseAppCheck.instance.activate(providerWeb: _releaseWebProvider);
  }

  // Connect to the local emulators before any Auth or Firestore call, because the SDKs cannot switch once used.
  if (kDebugMode && _useFirebaseEmulator) {
    try {
      await FirebaseAuth.instance.useAuthEmulator(devMachineIP, _authEmulatorPort);
      FirebaseFirestore.instance.useFirestoreEmulator(devMachineIP, _firestoreEmulatorPort);
      debugPrint('Using the Firebase emulators at $devMachineIP');
    } on Object catch (error) {
      debugPrint('Could not connect to the Firebase emulators: $error');
    }
  }

  // Sign in anonymously in the background. A failure is logged and tried again by the first code that needs the user.
  unawaited(
    AuthService.instance.ensureSignedIn().then<void>(
          (String userId) {},
          onError: (Object error) => debugPrint('Sign-in at launch failed: $error'),
        ),
  );

  // A web address with `?demo=true` starts the app with the simulated scale, so visitors need not find the demo menu.
  if (kIsWeb && DemoLaunch.isRequested(Uri.base)) {
    await ScaleService.instance.startDemo();
  }
  // Run the app.
  runApp(
    const Cupward(),
  );
}
